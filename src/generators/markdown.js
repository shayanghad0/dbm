/** Markdown documentation generator — includes a Mermaid ER diagram. */
export function generateMarkdown(schema, engine) {
  const terms = engine?.terms || { table: "Table", column: "Column", pk: "Primary Key" };
  const L = [];
  L.push(`# ${schema.name || "Database"}`);
  L.push("");
  L.push(`> Engine: **${engine?.label || schema.engine}** · ${(schema.tables || []).length} ${terms.table.toLowerCase()}s · ${(schema.relations || []).length} relations · generated by DB Easy Builder`);
  L.push("");

  // Mermaid ER diagram
  if (schema.tables?.length) {
    L.push("## Diagram");
    L.push("");
    L.push("```mermaid");
    L.push("erDiagram");
    for (const t of schema.tables) {
      const label = mermaidIdent(t.name);
      for (const c of t.columns.slice(0, 8)) {
        L.push(`  ${label} {`);
        L.push(`    ${mermaidIdent(engine?.typeIndex[c.type]?.native || c.type)} ${mermaidIdent(c.name)}`);
        L.push(`  }`);
      }
    }
    for (const r of schema.relations || []) {
      const st = schema.tables.find((t) => t.id === r.sourceTable);
      const tt = schema.tables.find((t) => t.id === r.targetTable);
      if (!st || !tt) continue;
      const card = { "1-n": "||--o{", "n-1": "o{--||", "1-1": "||--||", "n-m": "}o--o{" }[r.type] || "||--o{";
      const [left, right] = r.type === "n-1" ? [tt, st] : [st, tt];
      L.push(`  ${mermaidIdent(left.name)} ${card} ${mermaidIdent(right.name)} : ${mermaidIdent(r.type)}`);
    }
    L.push("```");
    L.push("");
  }

  L.push("## Tables");
  L.push("");
  for (const t of schema.tables || []) {
    L.push(`### ${t.name}`);
    if (t.note) {
      L.push("");
      L.push(`_${t.note}_`);
    }
    L.push("");
    L.push(`| ${terms.column} | Type | Length | Required | ${terms.pk} | Unique | Default |`);
    L.push("|---|---|---|:---:|:---:|:---:|---|");
    for (const c of t.columns || []) {
      const entry = engine?.typeIndex[c.type];
      const type = entry ? entry.native : c.type;
      L.push(
        `| \`${c.name}\` | ${type} | ${c.length || "—"} | ${c.required ? "✓" : ""} | ${c.primaryKey ? "🔑" : ""} | ${c.unique ? "✓" : ""} | ${c.defaultValue !== "" && c.defaultValue != null ? `\`${c.defaultValue}\`` : "—"} |`
      );
    }
    L.push("");
  }

  if (schema.relations?.length) {
    L.push("## Relations");
    L.push("");
    L.push("| From | To | Cardinality | On Delete | On Update |");
    L.push("|---|---|:---:|---|---|");
    for (const r of schema.relations) {
      const st = schema.tables.find((t) => t.id === r.sourceTable);
      const tt = schema.tables.find((t) => t.id === r.targetTable);
      const sc = st?.columns.find((c) => c.id === r.sourceColumn);
      const tc = tt?.columns.find((c) => c.id === r.targetColumn);
      L.push(`| \`${st?.name}.${sc?.name}\` | \`${tt?.name}.${tc?.name}\` | ${r.type} | ${r.onDelete || "—"} | ${r.onUpdate || "—"} |`);
    }
    L.push("");
  }

  return L.join("\n");
}

function mermaidIdent(s) {
  const clean = String(s || "x").replace(/[^A-Za-z0-9_]+/g, "_");
  return /^[0-9]/.test(clean) ? `_${clean}` : clean || "x";
}
