import { slugify } from "../lib/utils.js";

/**
 * Generic SQL generator driven by each engine's dialect config.
 * Handles: CREATE DATABASE (mysql/mssql), inline PK + identity, NOT NULL,
 * UNIQUE, DEFAULT, inline REFERENCES (postgres/sqlite/supabase), ALTER TABLE
 * ADD CONSTRAINT (mysql/mariadb/mssql/oracle), FK indexes (postgres).
 */
export function generateSql(schema, engine) {
  const d = engine.dialect;
  if (!d) throw new Error(`Engine "${engine.id}" has no SQL dialect`);
  const q = d.quote;
  const out = [];

  const title = schema.name || "database";
  out.push(`-- ${engine.label} schema for "${title}"`);
  out.push(`-- Generated by DB Easy Builder`);
  out.push("");

  if (d.headerPragma) out.push(d.headerPragma, "");

  if (d.createDatabase) {
    const dbName = q(slugify(title, "mydb"));
    if (engine.id === "mssql") {
      // T-SQL has no CREATE DATABASE IF NOT EXISTS
      out.push(`IF DB_ID(N'${slugify(title, "mydb")}') IS NULL`, `  CREATE DATABASE ${dbName};`, "GO", `USE ${dbName};`, "GO", "");
    } else {
      out.push(`CREATE DATABASE IF NOT EXISTS ${dbName};`, `USE ${dbName};`, "");
    }
  }

  // Resolve relations first — inline dialects need them while rendering columns.
  const inlineRefByCol = new Map(); // source column id -> { tt, tc, r }
  const alterFk = [];
  const fkIndexes = [];
  for (const r of schema.relations || []) {
    const st = schema.tables.find((t) => t.id === r.sourceTable);
    const tt = schema.tables.find((t) => t.id === r.targetTable);
    if (!st || !tt) continue;
    const sc = st.columns.find((c) => c.id === r.sourceColumn);
    const tc = tt.columns.find((c) => c.id === r.targetColumn);
    if (!sc || !tc) continue;

    if (d.inlineReferences) {
      inlineRefByCol.set(sc.id, { tt, tc, r });
    }
    if (d.fkAlter) {
      const name = `fk_${slugify(st.name, "t").slice(0, 30)}_${slugify(sc.name, "c").slice(0, 30)}`.replace(/-+/g, "_");
      alterFk.push(
        `ALTER TABLE ${q(st.name)}\n  ADD CONSTRAINT ${q(name)}\n  FOREIGN KEY (${q(sc.name)}) REFERENCES ${q(tt.name)} (${q(tc.name)})\n  ON DELETE ${r.onDelete || "NO ACTION"} ON UPDATE ${r.onUpdate || "NO ACTION"};`
      );
    }
    if (d.indexForFk) {
      fkIndexes.push(
        `CREATE INDEX idx_${slugify(st.name, "t")}_${slugify(sc.name, "c")}`.replace(/-+/g, "_") + ` ON ${q(st.name)} (${q(sc.name)});`
      );
    }
  }

  for (const t of schema.tables || []) {
    out.push(`-- ---- Table: ${t.name} ${t.note ? `(${t.note})` : ""} ----`);
    out.push(`CREATE TABLE ${q(t.name)} (`);

    const colLines = [];
    for (const c of t.columns || []) {
      colLines.push("  " + columnDef(c, engine, t, inlineRefByCol.get(c.id)));
    }
    out.push(colLines.join(",\n"));
    out.push(`)${d.tableOptions || ""};`);
    out.push("");
  }

  if (alterFk.length) {
    out.push(`-- ---- Foreign keys ----`);
    alterFk.forEach((stmt) => {
      out.push(stmt);
      out.push("");
    });
  }

  if (fkIndexes.length) {
    fkIndexes.forEach((stmt) => out.push(stmt));
    out.push("");
  }

  return out.join("\n") + "\n";
}

function columnDef(c, engine, table, ref = null) {
  const d = engine.dialect;
  const q = d.quote;
  const entry = engine.typeIndex[c.type];
  let native = entry?.native || "TEXT";
  let typeSql = native;
  const hasParens = native.includes("(");
  if (!hasParens && c.length && entry?.length) {
    typeSql = `${native}(${c.length})`;
  } else if (!hasParens && !c.length && entry?.defaultLength && entry.length === "chars") {
    typeSql = `${native}(${entry.defaultLength})`;
  } else if (!hasParens && !c.length && entry?.defaultLength && entry.length === "precision") {
    typeSql = `${native}(${entry.defaultLength})`;
  }

  if (c.type === "enum" && c.enumValues?.length) {
    const vals = c.enumValues.map((v) => `'${String(v).replace(/'/g, "''")}'`).join(", ");
    typeSql = `${native}(${vals})`;
  }

  const parts = [q(c.name), typeSql];

  if (c.primaryKey) {
    if (c.autoIncrement) {
      if (engine.id === "sqlite") {
        parts.push("PRIMARY KEY", "AUTOINCREMENT");
        return parts.join(" ") + trailingNote(c);
      }
      if (d.autoIncrement) parts.push(d.autoIncrement);
    }
    parts.push("PRIMARY KEY");
  } else {
    if (c.autoIncrement && d.autoIncrement) parts.push(d.autoIncrement);
    if (c.required) parts.push("NOT NULL");
    if (c.unique) parts.push("UNIQUE");
  }

  if (c.defaultValue !== "" && c.defaultValue != null) {
    parts.push("DEFAULT", defaultLiteral(c, engine));
  }

  if (ref) {
    parts.push(
      `REFERENCES ${q(ref.tt.name)} (${q(ref.tc.name)})`,
      `ON DELETE ${ref.r.onDelete || "NO ACTION"} ON UPDATE ${ref.r.onUpdate || "NO ACTION"}`
    );
  }

  return parts.join(" ") + trailingNote(c);
}

function trailingNote(c) {
  return c.note ? ` -- ${c.note}` : "";
}

function defaultLiteral(c, engine) {
  const v = String(c.defaultValue);
  const d = engine.dialect;
  if (d.booleanTrue && /^(true|yes)$/i.test(v)) return d.booleanTrue;
  if (d.booleanFalse && /^(false|no)$/i.test(v)) return d.booleanFalse;
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  if (/^(current_timestamp|now\(\)|current_date)$/i.test(v)) return "CURRENT_TIMESTAMP";
  return `'${v.replace(/'/g, "''")}'`;
}
