/**
 * Prisma schema generator.
 * - model names: PascalCase; fields: camelCase (duplicates get suffixes)
 * - types mapped from logical types; enums generated from enumValues
 * - relations: fk side @relation(fields:[...], references:[...]) + back-relation list
 */
export function generatePrisma(schema, engine) {
  const provider = engine.supports?.prismaProvider || "postgresql";
  const isMongo = provider === "mongodb";
  const L = [];

  L.push(`// Prisma schema for "${schema.name || "database"}"`);
  L.push(`// Generated by DB Easy Builder — docs: https://pris.ly/d/prisma-schema`);
  L.push(``);
  L.push(`generator client {`);
  L.push(`  provider = "prisma-client-js"`);
  L.push(`}`);
  L.push(``);
  L.push(`datasource db {`);
  L.push(`  provider = "${provider}"`);
  L.push(`  url      = env("DATABASE_URL")`);
  L.push(`}`);

  const tables = schema.tables || [];

  // model names + unique/back-relation field name registry
  const modelOf = new Map(); // tableId -> { name, fields:Set }
  for (const t of tables) {
    modelOf.set(t.id, { name: pascal(t.name), fields: new Set() });
  }

  // enums
  const enums = [];
  for (const t of tables) {
    for (const c of t.columns || []) {
      if (c.type === "enum" && c.enumValues?.length) {
        const ename = `${pascal(t.name)}${pascal(c.name)}`;
        enums.push({ name: ename, values: c.enumValues, tableId: t.id, colId: c.id });
      }
    }
  }
  const enumFor = new Map();
  enums.forEach((e) => enumFor.set(`${e.tableId}:${e.colId}`, e));

  for (const e of enums) {
    L.push(``);
    L.push(`enum ${e.name} {`);
    for (const v of e.values) L.push(`  ${ident(v)}`);
    L.push(`}`);
  }

  // relations grouped for back-relations
  const rels = (schema.relations || [])
    .map((r) => {
      const st = tables.find((t) => t.id === r.sourceTable);
      const tt = tables.find((t) => t.id === r.targetTable);
      if (!st || !tt) return null;
      const sc = st.columns.find((c) => c.id === r.sourceColumn);
      const tc = tt.columns.find((c) => c.id === r.targetColumn);
      return { r, st, tt, sc, tc };
    })
    .filter(Boolean)
    .filter((x) => x.sc && x.tc);

  for (const t of tables) {
    const m = modelOf.get(t.id);
    L.push(``);
    L.push(`model ${m.name} {`);
    const used = new Set();

    for (const c of t.columns || []) {
      let field = camel(c.name) || "field";
      while (used.has(field)) field = field + "_";
      used.add(field);
      m.fields.add(field);

      const enumEntry = enumFor.get(`${t.id}:${c.id}`);
      const prismaType = enumEntry ? enumEntry.name : scalarType(c, engine, isMongo);
      const opt = c.required ? "" : "?";
      const attrs = [];
      if (c.primaryKey) {
        attrs.push("@id");
        if (isMongo) attrs.push('@default(auto()) @map("_id")');
        else if (c.autoIncrement) attrs.push("@default(autoincrement())");
        else if (c.type === "uuid") attrs.push("@default(uuid())");
      } else {
        if (c.unique) attrs.push("@unique");
        if (c.autoIncrement) attrs.push("@default(autoincrement())");
        if (c.type === "uuid") attrs.push("@default(uuid())");
        if (c.defaultValue !== "" && c.defaultValue != null) {
          const v = String(c.defaultValue);
          if (/^(current_timestamp|now\(\))$/i.test(v)) attrs.push("@default(now())");
          else if (/^-?\d+(\.\d+)?$/.test(v)) attrs.push(`@default(${v})`);
          else if (/^true$/i.test(v)) attrs.push("@default(true)");
          else if (/^false$/i.test(v)) attrs.push("@default(false)");
          else attrs.push(`@default("${v.replace(/"/g, '\\"')}")`);
        }
      }
      L.push(`  ${field} ${prismaType}${opt}${attrs.length ? " " + attrs.join(" ") : ""}`);
    }

    // relation fields on the fk side
    const myRels = rels.filter((x) => x.st.id === t.id && x.r.type !== "n-m");
    for (const x of myRels) {
      const target = modelOf.get(x.tt.id);
      let field = lowerCamel(target.name);
      while (used.has(field)) field = field + "_";
      used.add(field);
      const list = "";
      const opt = x.r.type === "1-1" ? (x.sc.required ? "" : "?") : "?";
      const actions = [];
      if (x.r.onDelete && x.r.onDelete !== "NO ACTION") actions.push(`onDelete: ${prismaAction(x.r.onDelete)}`);
      if (x.r.onUpdate && x.r.onUpdate !== "NO ACTION") actions.push(`onUpdate: ${prismaAction(x.r.onUpdate)}`);
      const relationArgs = `fields: [${camel(x.sc.name)}], references: [${camel(x.tc.name)}]${actions.length ? ", " + actions.join(", ") : ""}`;
      L.push(`  ${field} ${target.name}${opt} @relation(${relationArgs})`);
    }

    // implicit m-n fields
    const mnOut = rels.filter((x) => x.st.id === t.id && x.r.type === "n-m");
    const mnIn = rels.filter((x) => x.tt.id === t.id && x.r.type === "n-m");
    for (const x of [...mnOut, ...mnIn]) {
      const other = modelOf.get(x.st.id === t.id ? x.tt.id : x.st.id);
      let field = pluralize(lowerCamel(other.name));
      while (used.has(field)) field = field + "_";
      used.add(field);
      L.push(`  ${field} ${other.name}[] @relation("${pascal(x.st.name)}_${pascal(x.tt.name)}")`);
    }

    // back-relation fields (lists on referenced side)
    const incoming = rels.filter((x) => x.tt.id === t.id && x.r.type !== "n-m");
    for (const x of incoming) {
      const source = modelOf.get(x.st.id);
      let field = x.r.type === "1-1" ? lowerCamel(source.name) : pluralize(lowerCamel(source.name));
      while (used.has(field)) field = field + "_";
      used.add(field);
      const opt = x.r.type === "1-1" ? "?" : "[]";
      L.push(`  ${field} ${source.name}${opt}`);
    }

    L.push(`}`);
  }

  return L.join("\n") + "\n";
}

function scalarType(c, engine, isMongo) {
  const t = c.type;
  if (isMongo) {
    const map = { string: "String", text: "String", integer: "Int", bigint: "BigInt", float: "Float", decimal: "Decimal", boolean: "Boolean", date: "DateTime", datetime: "DateTime", objectId: "String", json: "Json", object: "Json", array: "Json", blob: "Bytes" };
    return map[t] || "String";
  }
  const map = { string: "String", text: "String", integer: "Int", bigint: "BigInt", float: "Float", decimal: "Decimal", boolean: "Boolean", date: "DateTime", time: "DateTime", datetime: "DateTime", json: "Json", uuid: "String", blob: "Bytes" };
  let base = map[t] || "String";
  if (engine.id === "postgresql" && t === "uuid") base = "String @db.Uuid";
  if (engine.id === "postgresql" && t === "date") base = "DateTime @db.Date";
  return base;
}

function prismaAction(v) {
  const map = { CASCADE: "Cascade", "SET NULL": "SetNull", RESTRICT: "Restrict", "NO ACTION": "NoAction", "SET DEFAULT": "SetDefault" };
  return map[v] || "NoAction";
}

function pascal(s) {
  return (s || "Model")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("") || "Model";
}

function camel(s) {
  const p = (s || "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (!p.length) return "";
  return p[0].charAt(0).toLowerCase() + p.slice(0).map((w, i) => (i === 0 ? "" : w.charAt(0).toUpperCase() + w.slice(1))).join("") + p.slice(1).join("");
}

function lowerCamel(s) {
  const pc = pascal(s);
  return pc.charAt(0).toLowerCase() + pc.slice(1);
}

function pluralize(s) {
  return /[sxz]$/.test(s) ? s + "es" : s + "s";
}

function ident(v) {
  const s = String(v).toUpperCase().replace(/[^A-Z0-9_]+/g, "_").replace(/^(\d)/, "_$1");
  return s || "VALUE";
}
