import { makeEngine, baseValidate, quotes, T, TYPE_GROUPS } from "../base.js";
import POSTGRESQL from "./postgresql.js";

/** Supabase — PostgreSQL with Auth, RLS and instant APIs */
const ENGINE = makeEngine({
  ...POSTGRESQL,
  id: "supabase",
  label: "Supabase",
  desc: "Postgres-based platform with Auth, instant APIs and Row Level Security built in.",
  descFa: "پلتفرم مبتنی بر PostgreSQL با احراز هویت، API فوری و Row Level Security داخلی.",
  color: "#3ECF8E",
  ext: "sql",
  supports: { sql: true, prisma: true, prismaProvider: "postgresql", native: true, json: true },
  dialect: {
    ...POSTGRESQL.dialect,
    rls: true,
  },
  validate(schema) {
    return baseValidate(schema, this, { identifier: /^[A-Za-z_][A-Za-z0-9_]*$/ });
  },
  /** Supabase export = Postgres SQL + RLS policies */
  generate(schema) {
    return buildSupabase(schema, this);
  },
});

function buildSupabase(schema, engine) {
  const q = engine.dialect.quote;
  const lines = [];
  lines.push(`-- Supabase schema for "${schema.name || "database"}"`);
  lines.push(`-- Generated by DB Easy Builder`);
  lines.push(``);
  lines.push(`-- -------------------------------------------------`);
  lines.push(`-- Tables (PostgreSQL)`);
  for (const t of schema.tables || []) {
    lines.push(``);
    lines.push(`CREATE TABLE IF NOT EXISTS ${q(t.name)} (`);
    lines.push(t.columns.map((c) => "  " + columnSql(c, engine, t)).join(",\n"));
    lines.push(`);`);
    if (t.note) lines.push(`COMMENT ON TABLE ${q(t.name)} IS '${t.note.replace(/'/g, "''")}';`);
  }
  lines.push(``);
  lines.push(`-- -------------------------------------------------`);
  lines.push(`-- Row Level Security`);
  for (const t of schema.tables || []) {
    lines.push(`ALTER TABLE ${q(t.name)} ENABLE ROW LEVEL SECURITY;`);
  }
  lines.push(``);
  lines.push(`-- Authenticated users can read/write (adjust to your needs)`);
  for (const t of schema.tables || []) {
    lines.push(`CREATE POLICY "authenticated_full_access" ON ${q(t.name)}`);
    lines.push(`  FOR ALL TO authenticated`);
    lines.push(`  USING (true)`);
    lines.push(`  WITH CHECK (true);`);
  }
  return lines.join("\n") + "\n";
}

function columnSql(c, engine) {
  const entry = engine.typeIndex[c.type];
  let native = entry?.native || "TEXT";
  let suffix = "";
  if (c.primaryKey) suffix += " PRIMARY KEY";
  else if (c.required) suffix += " NOT NULL";
  if (c.unique && !c.primaryKey) suffix += " UNIQUE";
  if (c.defaultValue !== "" && c.defaultValue != null) suffix += ` DEFAULT ${defaultLiteral(c, engine)}`;
  if (c.note) suffix += ` -- ${c.note}`;
  return `${engine.dialect.quote(c.name)} ${native}${suffix}`;
}

function defaultLiteral(c, engine) {
  const v = String(c.defaultValue);
  const d = engine.dialect;
  if (d.booleanTrue && /^(true)$/i.test(v)) return d.booleanTrue;
  if (d.booleanFalse && /^(false)$/i.test(v)) return d.booleanFalse;
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  if (/^CURRENT_TIMESTAMP$/i.test(v) || /^now\(\)$/i.test(v)) return "now()";
  return `'${v.replace(/'/g, "''")}'`;
}

export default ENGINE;
