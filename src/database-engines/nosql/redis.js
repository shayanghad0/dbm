import { makeEngine, baseValidate, T, TYPE_GROUPS } from "../base.js";

/** Redis — in-memory key-value store (keyspace design model) */
const ENGINE = makeEngine({
  id: "redis",
  family: "nosql",
  label: "Redis",
  desc: "Ultra-fast in-memory store. Modelled here as keyspaces: keys, hashes, sets and streams.",
  descFa: "ذخیره‌ساز فوق‌سریع درون‌حافظه‌ای. در اینجا به شکل keyspace مدل می‌شود: کلید، hash، set و stream.",
  color: "#DC382D",
  ext: "redis",
  terms: { table: "Keyspace", column: "Field", pk: "Key", tableFa: "Keyspace", columnFa: "فیلد", pkFa: "کلید" },
  supports: { sql: false, prisma: false, native: true, json: true },
  defaultType: "hash",
  types: [
    T("hash", "HASH"),
    T("string", "STRING"),
    T("list", "LIST", { group: TYPE_GROUPS.other }),
    T("set", "SET", { group: TYPE_GROUPS.other }),
    T("sortedSet", "ZSET", { group: TYPE_GROUPS.other }),
    T("stream", "STREAM", { group: TYPE_GROUPS.other }),
    T("json", "JSON", { group: TYPE_GROUPS.other }),
    T("counter", "COUNTER", { group: TYPE_GROUPS.numbers }),
    T("integer", "INTEGER", { group: TYPE_GROUPS.numbers }),
  ],
  aliases: { hash: "hash", string: "string", list: "list", set: "set", zset: "sortedSet", stream: "stream", counter: "counter" },
  validate(schema) {
    return baseValidate(schema, this, { sqlish: false, identifier: /^[a-z][a-z0-9:_-]*$/, reserved: [] });
  },
  /** Export: documented keyspace conventions + sample commands */
  generate(schema) {
    const lines = [];
    lines.push(`# Redis keyspace design for "${schema.name || "database"}"`);
    lines.push(`# Generated by DB Easy Builder`);
    lines.push(`# Conventions: object keys -> "<object>:<id>", lookups -> "<object>:by:<field>"`);
    for (const t of schema.tables || []) {
      lines.push(``);
      lines.push(`# ---- ${t.name} ${t.note ? `(${t.note})` : ""} ----`);
      const keyType = (t.columns || []).find((c) => c.primaryKey)?.type || "hash";
      lines.push(`# Key pattern: ${t.name.toLowerCase()}:{${keyType === "hash" ? "id" : "key"}} -> ${keyType.toUpperCase()}`);
      for (const c of t.columns || []) {
        if (c.primaryKey) continue;
        lines.push(`#   field: ${c.name} (${c.type})${c.required ? " [required]" : ""}${c.unique ? " [unique index]" : ""}`);
      }
      const pk = (t.columns || []).find((c) => c.primaryKey);
      lines.push(``);
      lines.push(`# Example commands`);
      lines.push(`# HSET ${t.name.toLowerCase()}:1 ${t.columns.filter((c) => !c.primaryKey).slice(0, 4).map((c) => `${c.name} "${c.defaultValue || "value"}"`).join(" ")}`);
      if (t.columns.some((c) => c.unique && !c.primaryKey)) {
        const u = t.columns.find((c) => c.unique && !c.primaryKey);
        lines.push(`# SET ${t.name.toLowerCase()}:by:${u.name} <value> -> stores id (unique index)`);
      }
      if (t.columns.some((c) => c.type === "counter")) {
        lines.push(`# INCR ${t.name.toLowerCase()}:counters`);
      }
      if (pk) lines.push(`# GET ${t.name.toLowerCase()}:1`);
    }
    return lines.join("\n") + "\n";
  },
});

export default ENGINE;
