import { makeEngine, baseValidate, T, TYPE_GROUPS } from "../base.js";

/** Apache Cassandra — wide-column distributed database (CQL) */
const ENGINE = makeEngine({
  id: "cassandra",
  family: "nosql",
  label: "Cassandra",
  desc: "Distributed wide-column database with CQL — built for scale and high write throughput.",
  descFa: "پایگاه‌داده توزیع‌شده wide-column با CQL — مناسب مقیاس بالا و حجم بالای نوشتن.",
  color: "#1287B1",
  ext: "cql",
  terms: { table: "Table", column: "Column", pk: "Partition Key", tableFa: "جدول", columnFa: "ستون", pkFa: "کلید Partition" },
  supports: { sql: false, prisma: false, native: true, json: true },
  defaultType: "text",
  types: [
    T("text", "text"),
    T("string", "text"),
    T("integer", "int", { group: TYPE_GROUPS.numbers }),
    T("bigint", "bigint", { group: TYPE_GROUPS.numbers }),
    T("float", "float", { group: TYPE_GROUPS.numbers }),
    T("decimal", "decimal", { group: TYPE_GROUPS.numbers }),
    T("boolean", "boolean", { group: TYPE_GROUPS.boolean }),
    T("date", "date", { group: TYPE_GROUPS.datetime }),
    T("datetime", "timestamp", { group: TYPE_GROUPS.datetime }),
    T("time", "time", { group: TYPE_GROUPS.datetime }),
    T("timeuuid", "timeuuid", { group: TYPE_GROUPS.other }),
    T("uuid", "uuid", { group: TYPE_GROUPS.other }),
    T("blob", "blob", { group: TYPE_GROUPS.other }),
    T("list", "list<text>", { group: TYPE_GROUPS.other }),
    T("set", "set<text>", { group: TYPE_GROUPS.other }),
    T("map", "map<text, text>", { group: TYPE_GROUPS.other }),
    T("counter", "counter", { group: TYPE_GROUPS.numbers }),
  ],
  aliases: { text: "text", int: "integer", bigint: "bigint", float: "float", double: "float", decimal: "decimal", boolean: "boolean", date: "date", timestamp: "datetime", timeuuid: "timeuuid", uuid: "uuid", blob: "blob", counter: "counter" },
  identifier: /^[A-Za-z_][A-Za-z0-9_]*$/,
  validate(schema) {
    const issues = baseValidate(schema, this, { sqlish: false, identifier: /^[A-Za-z_][A-Za-z0-9_]*$/ });
    for (const t of schema.tables || []) {
      if ((t.columns || []).length && !(t.columns || []).some((c) => c.primaryKey)) {
        issues.push({ level: "error", code: "MISSING_PARTITION_KEY", tableId: t.id, params: { name: t.name }, message: `Table "${t.name}" needs at least one Partition Key column.` });
      }
    }
    return issues;
  },
  /** Export: CQL keyspace + tables */
  generate(schema) {
    const keyspace = (schema.name || "mydb").trim().toLowerCase().replace(/[^a-z0-9_]+/g, "_") || "mydb";
    const lines = [];
    lines.push(`-- Cassandra CQL schema for "${schema.name || "database"}"`);
    lines.push(`-- Generated by DB Easy Builder`);
    lines.push(``);
    lines.push(`CREATE KEYSPACE IF NOT EXISTS ${keyspace}`);
    lines.push(`  WITH replication = {'class': 'NetworkTopologyStrategy', 'datacenter1': 3};`);
    lines.push(``);
    lines.push(`USE ${keyspace};`);
    for (const t of schema.tables || []) {
      lines.push(``);
      lines.push(`CREATE TABLE IF NOT EXISTS ${t.name} (`);
      const pkCols = (t.columns || []).filter((c) => c.primaryKey);
      const others = (t.columns || []).filter((c) => !c.primaryKey);
      const colDefs = (t.columns || []).map((c) => {
        const entry = this.typeIndex[c.type];
        return `  ${c.name} ${entry?.native || "text"}${c.note ? ` -- ${c.note}` : ""}`;
      });
      if (pkCols.length) {
        const pk = pkCols.length === 1 ? pkCols[0].name : `(${pkCols[0].name}), ${pkCols.slice(1).map((c) => c.name).join(", ")}`;
        colDefs.push(`  PRIMARY KEY (${pk})`);
      }
      lines.push(colDefs.join(",\n"));
      lines.push(`);`);
      if (others.some((c) => c.unique && !c.primaryKey)) {
        const u = others.find((c) => c.unique);
        lines.push(`-- Unique lookup: CREATE CUSTOM INDEX ON ${t.name} (${u.name});`);
      }
    }
    return lines.join("\n") + "\n";
  },
});

export default ENGINE;
