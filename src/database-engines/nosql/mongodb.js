import { makeEngine, baseValidate, T, TYPE_GROUPS } from "../base.js";

/** MongoDB — document database (schema modelled via $jsonSchema validators) */
const ENGINE = makeEngine({
  id: "mongodb",
  family: "nosql",
  label: "MongoDB",
  desc: "Document database with flexible JSON-like documents and rich queries.",
  descFa: "پایگاه‌داده سند‌محور با اسناد انعطاف‌پذیر شبیه JSON و کوئری‌های قدرتمند.",
  color: "#47A248",
  ext: "js",
  terms: { table: "Collection", column: "Field", pk: "_id", tableFa: "کالکشن", columnFa: "فیلد", pkFa: "کلید _id" },
  supports: { sql: false, prisma: true, prismaProvider: "mongodb", native: true, json: true },
  defaultType: "string",
  types: [
    T("string", "string"),
    T("text", "string"),
    T("integer", "int", { group: TYPE_GROUPS.numbers }),
    T("bigint", "long", { group: TYPE_GROUPS.numbers }),
    T("float", "double", { group: TYPE_GROUPS.numbers }),
    T("decimal", "decimal", { group: TYPE_GROUPS.numbers }),
    T("boolean", "bool", { group: TYPE_GROUPS.boolean }),
    T("date", "date", { group: TYPE_GROUPS.datetime }),
    T("objectId", "objectId", { group: TYPE_GROUPS.other }),
    T("json", "object", { group: TYPE_GROUPS.other }),
    T("object", "object", { group: TYPE_GROUPS.other }),
    T("array", "array", { group: TYPE_GROUPS.other }),
    T("blob", "binData", { group: TYPE_GROUPS.other }),
  ],
  aliases: {
    string: "string", int: "integer", long: "bigint", double: "float",
    decimal: "decimal", bool: "boolean", date: "date", timestamp: "date",
    objectid: "objectId", object: "object", array: "array", bindata: "blob",
  },
  identifier: /^[A-Za-z][A-Za-z0-9_]*$/,
  validate(schema) {
    const issues = baseValidate(schema, this, {
      sqlish: false,
      identifier: /^[A-Za-z][A-Za-z0-9_]*$/,
      reserved: [],
    });
    for (const t of schema.tables || []) {
      for (const c of t.columns || []) {
        const n = c.name || "";
        if (n.includes(".") || n.includes("$") || n.startsWith("_id")) {
          issues.push({ level: "warning", code: "MONGO_FIELD_NAME", tableId: t.id, columnId: c.id, params: { name: n }, message: `Field "${n}" should avoid ".", "$" and "_id" prefix (reserved by MongoDB).` });
        }
      }
    }
    if (schema.relations?.length) {
      issues.push({ level: "warning", code: "MONGO_REFERENCES", message: "MongoDB does not enforce foreign keys — references are handled in your application layer." });
    }
    return issues;
  },
  /** Export: mongosh script with $jsonSchema validators + indexes */
  generate(schema) {
    const dbName = slugName(schema.name);
    const lines = [];
    lines.push(`// MongoDB setup for "${schema.name || "database"}"`);
    lines.push(`// Generated by DB Easy Builder — run with: mongosh`);
    lines.push(``);
    lines.push(`use("${dbName}");`);
    for (const t of schema.tables || []) {
      const required = (t.columns || []).filter((c) => c.required).map((c) => c.name);
      const props = {};
      for (const c of t.columns || []) {
        const entry = this.typeIndex[c.type];
        if (!entry) continue;
        const p = { bsonType: entry.native, description: c.note || `${c.name}` };
        if (c.enumValues?.length) p.enum = [...c.enumValues];
        props[c.name] = p;
      }
      lines.push(``);
      lines.push(`db.createCollection("${t.name}", {`);
      lines.push(`  validator: {`);
      lines.push(`    $jsonSchema: {`);
      lines.push(`      bsonType: "object",`);
      lines.push(`      title: "${t.name}",`);
      if (required.length) {
        lines.push(`      required: ${JSON.stringify(required)},`);
      }
      lines.push(`      properties: ${JSON.stringify(props, null, 6).replace(/\n/g, "\n      ").replace(/\n {6}/g, "\n").replace(/\n$/, "\n      ")}`);
      lines.push(`      }`);
      lines.push(`  }`);
      lines.push(`});`);
      const unique = (t.columns || []).filter((c) => c.unique && c.name !== "_id");
      for (const c of unique) {
        lines.push(`db.${t.name}.createIndex({ ${c.name}: 1 }, { unique: true });`);
      }
    }
    return lines.join("\n") + "\n";
  },
});

function slugName(name) {
  return (name || "mydb").trim().toLowerCase().replace(/[^a-z0-9_]+/g, "_").replace(/^_+|_+$/g, "") || "mydb";
}

export default ENGINE;
