import { makeEngine, baseValidate, T, TYPE_GROUPS } from "../base.js";

/** Neo4j — graph database (labels, properties, relationships) */
const ENGINE = makeEngine({
  id: "neo4j",
  family: "nosql",
  label: "Neo4j",
  desc: "Graph database — design node labels with properties and typed relationships.",
  descFa: "پایگاه‌داده گرافی — طراحی لیبل‌های گره با پراپرتی‌ها و رابطه‌های نوع‌دار.",
  color: "#008CC1",
  ext: "cypher",
  terms: { table: "Node Label", column: "Property", pk: "Unique Property", tableFa: "لیبل گره", columnFa: "پراپرتی", pkFa: "پراپرتی یکتا" },
  supports: { sql: false, prisma: false, native: true, json: true },
  defaultType: "string",
  types: [
    T("string", "STRING"),
    T("integer", "INTEGER", { group: TYPE_GROUPS.numbers }),
    T("float", "FLOAT", { group: TYPE_GROUPS.numbers }),
    T("boolean", "BOOLEAN", { group: TYPE_GROUPS.boolean }),
    T("datetime", "DATETIME", { group: TYPE_GROUPS.datetime }),
    T("date", "DATE", { group: TYPE_GROUPS.datetime }),
    T("time", "TIME", { group: TYPE_GROUPS.datetime }),
    T("point", "POINT", { group: TYPE_GROUPS.other }),
    T("array", "LIST", { group: TYPE_GROUPS.other }),
  ],
  aliases: { string: "string", integer: "integer", float: "float", boolean: "boolean", datetime: "datetime", date: "date", time: "time", point: "point", array: "array", list: "array" },
  identifier: /^[A-Z][A-Za-z0-9]*$/,
  validate(schema) {
    const issues = baseValidate(schema, this, { sqlish: false, identifier: /^[A-Za-z][A-Za-z0-9_]*$/, reserved: [] });
    for (const t of schema.tables || []) {
      if (/^[a-z]/.test(t.name || "")) {
        issues.push({ level: "warning", code: "NEO4J_LABEL_CASE", tableId: t.id, params: { name: t.name }, message: `Node label "${t.name}" should start with an uppercase letter (PascalCase).` });
      }
    }
    return issues;
  },
  /** Export: Cypher constraints + sample MERGE statements */
  generate(schema) {
    const lines = [];
    lines.push(`// Neo4j graph schema for "${schema.name || "database"}"`);
    lines.push(`// Generated by DB Easy Builder — run in Browser / cypher-shell`);
    lines.push(``);
    for (const t of schema.tables || []) {
      const uniqueProp = (t.columns || []).find((c) => c.primaryKey) || (t.columns || [])[0];
      if (uniqueProp) {
        lines.push(`CREATE CONSTRAINT ${snake(t.name)}_${snake(uniqueProp.name)}_unique IF NOT EXISTS`);
        lines.push(`  FOR (n:${t.name}) REQUIRE n.${uniqueProp.name} IS UNIQUE;`);
      }
    }
    lines.push(``);
    lines.push(`// Sample nodes`);
    for (const t of schema.tables || []) {
      const props = (t.columns || [])
        .slice(0, 5)
        .map((c) => `${c.name}: $${c.name}`)
        .join(", ");
      lines.push(`MERGE (n:${t.name} { ${props} });`);
    }
    lines.push(``);
    lines.push(`// Sample relationships`);
    for (const r of schema.relations || []) {
      const st = schema.tables.find((t) => t.id === r.sourceTable);
      const tt = schema.tables.find((t) => t.id === r.targetTable);
      if (!st || !tt) continue;
      const relName = r.type === "n-m" ? "RELATED_TO" : snake(`HAS_${r.type}`) || "RELATES_TO";
      lines.push(`MATCH (a:${st.name}), (b:${tt.name})`);
      lines.push(`  MERGE (a)-[:${relName}]->(b);`);
    }
    return lines.join("\n") + "\n";
  },
});

function snake(s) {
  return (s || "").replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

export default ENGINE;
