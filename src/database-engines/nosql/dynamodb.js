import { makeEngine, baseValidate, T, TYPE_GROUPS } from "../base.js";

/** Amazon DynamoDB — NoSQL key-value / document store */
const ENGINE = makeEngine({
  id: "dynamodb",
  family: "nosql",
  label: "DynamoDB",
  desc: "AWS serverless NoSQL database. Design partition/sort keys, attributes and indexes.",
  descFa: "پایگاه‌داده NoSQL بدون سرور AWS. طراحی کلیدهای partition/sort، ویژگی‌ها و ایندکس‌ها.",
  color: "#527FFF",
  ext: "js",
  terms: { table: "Table", column: "Attribute", pk: "Partition Key", tableFa: "جدول", columnFa: "ویژگی", pkFa: "کلید Partition" },
  supports: { sql: false, prisma: false, native: true, json: true },
  defaultType: "string",
  types: [
    T("string", "S"),
    T("integer", "N", { group: TYPE_GROUPS.numbers }),
    T("bigint", "N", { group: TYPE_GROUPS.numbers }),
    T("float", "N", { group: TYPE_GROUPS.numbers }),
    T("decimal", "N", { group: TYPE_GROUPS.numbers }),
    T("boolean", "BOOL", { group: TYPE_GROUPS.boolean }),
    T("date", "S", { group: TYPE_GROUPS.datetime }),
    T("datetime", "S", { group: TYPE_GROUPS.datetime }),
    T("blob", "B", { group: TYPE_GROUPS.other }),
    T("list", "L", { group: TYPE_GROUPS.other }),
    T("object", "M", { group: TYPE_GROUPS.other }),
    T("stringSet", "SS", { group: TYPE_GROUPS.other }),
    T("numberSet", "NS", { group: TYPE_GROUPS.other }),
    T("binarySet", "BS", { group: TYPE_GROUPS.other }),
  ],
  aliases: { s: "string", n: "integer", b: "blob", bool: "boolean", l: "list", m: "object", ss: "stringSet", ns: "numberSet", bs: "binarySet" },
  validate(schema) {
    const issues = baseValidate(schema, this, { sqlish: false, identifier: /^[A-Za-z0-9_.-]+$/, reserved: [] });
    for (const t of schema.tables || []) {
      const partition = partitionKeyOf(t);
      const explicitPartitions = (t.columns || []).filter((c) => c.flag === "partition");
      if (!partition) {
        issues.push({ level: "error", code: "MISSING_PARTITION_KEY", tableId: t.id, params: { name: t.name }, message: `Table "${t.name}" needs exactly one Partition Key (mark an attribute as PK).` });
      } else if (explicitPartitions.length > 1) {
        issues.push({ level: "error", code: "TOO_MANY_PARTITION_KEYS", tableId: t.id, params: { name: t.name }, message: `Table "${t.name}" can only have one Partition Key.` });
      }
      if ((t.columns || []).filter((c) => c.flag === "sort").length > 1) {
        issues.push({ level: "error", code: "TOO_MANY_SORT_KEYS", tableId: t.id, params: { name: t.name }, message: `Table "${t.name}" can have at most one Sort Key (use the details dialog).` });
      }
    }
    return issues;
  },
  /** Normalize plain primary keys into DynamoDB partition keys (templates/imports). */
  normalize(schema) {
    for (const t of schema.tables || []) {
      const cols = t.columns || [];
      const hasKeyFlag = cols.some((c) => c.flag === "partition" || c.flag === "sort");
      if (!hasKeyFlag) {
        const pk = cols.find((c) => c.primaryKey) || cols[0];
        if (pk) pk.flag = "partition";
      }
    }
    return schema;
  },
  /** Export: AWS SDK v3 JavaScript with CreateTable commands */
  generate(schema) {
    const lines = [];
    lines.push(`// DynamoDB tables for "${schema.name || "database"}"`);
    lines.push(`// Generated by DB Easy Builder`);
    lines.push(`// Requires: npm i @aws-sdk/client-dynamodb`);
    lines.push(`import { DynamoDBClient, CreateTableCommand } from "@aws-sdk/client-dynamodb";`);
    lines.push(``);
    lines.push(`const client = new DynamoDBClient({ region: "us-east-1" });`);
    lines.push(``);
    for (const t of schema.tables || []) {
      const partition = partitionKeyOf(t);
      const sort = sortKeyOf(t);
      if (!partition) continue;
      const attrs = [];
      const seen = new Set();
      for (const c of [partition, sort].filter(Boolean)) {
        if (seen.has(c.name)) continue;
        seen.add(c.name);
        attrs.push({ AttributeName: c.name, AttributeType: this.typeIndex[c.type]?.native || "S" });
      }
      const keySchema = [{ AttributeName: partition.name, KeyType: "HASH" }];
      if (sort) keySchema.push({ AttributeName: sort.name, KeyType: "RANGE" });
      lines.push(`export const create${pascal(t.name)} = async () => {`);
      lines.push(`  const command = new CreateTableCommand({`);
      lines.push(`    TableName: "${t.name}",`);
      lines.push(`    KeySchema: ${JSON.stringify(keySchema)},`);
      lines.push(`    AttributeDefinitions: ${JSON.stringify(attrs)},`);
      lines.push(`    BillingMode: "PAY_PER_REQUEST",`);
      lines.push(`  });`);
      lines.push(`  return client.send(command);`);
      lines.push(`};`);
      lines.push(``);
      const sample = {};
      for (const c of t.columns || []) {
        if (c.name === partition.name || (sort && c.name === sort.name)) continue;
        if (c.type === "integer" || c.type === "bigint" || c.type === "float") sample[c.name] = 0;
        else if (c.type === "boolean") sample[c.name] = false;
        else sample[c.name] = "value";
      }
      lines.push(`// Sample item for ${t.name}:`);
      lines.push(`// { ${Object.entries(sample).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ")} }`);
      lines.push(``);
    }
    return lines.join("\n") + "\n";
  },
});

/** Partition key: explicit flag wins, otherwise the primary key (templates/imports). */
function partitionKeyOf(table) {
  const cols = table.columns || [];
  return cols.find((c) => c.flag === "partition") || cols.find((c) => c.primaryKey) || null;
}

/** Sort key: only ever set explicitly via the column details dialog. */
function sortKeyOf(table) {
  return (table.columns || []).find((c) => c.flag === "sort") || null;
}

function pascal(s) {
  return (s || "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("") || "Table";
}

export default ENGINE;
